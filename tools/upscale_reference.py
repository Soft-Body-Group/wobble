"""Reference numbers for engine/tests/upscale.rs, from the upstream torch
architectures (via spandrel) run on the same .pth files wobble reads.

    uv venv -p 3.12 .venv && uv pip install torch spandrel numpy
    .venv/bin/python tools/upscale_reference.py ~/.wobble/models > engine/tests/upscale_ref.rs

Run once; the output is committed. The input is a smooth 10x8 picture the
test builds with the same formula.
"""
import math, sys, os
import numpy as np
import torch
import spandrel

W, H, N = 10, 8, 256
MODELS = [
    ("COMPACT", "realesr-general-x4v3.pth"),
    ("X4PLUS", "RealESRGAN_x4plus.pth"),
    ("SPAN", "4xNomosUni_span_multijpg.pth"),
]

def picture():
    a = np.zeros((3, H, W), dtype=np.float64)
    for c in range(3):
        for y in range(H):
            for x in range(W):
                a[c, y, x] = 0.5 + 0.4 * math.sin(0.9 * x + 1.7 * c) * math.cos(0.7 * y - 0.3 * c)
    return a.astype(np.float32)

def main():
    d = sys.argv[1]
    x = torch.from_numpy(picture())[None]
    print("// Generated by tools/upscale_reference.py: torch", torch.__version__,
          "spandrel", spandrel.__version__, "— do not edit.")
    print(f"pub const W: usize = {W};\npub const H: usize = {H};\npub const N: usize = {N};")
    for name, f in MODELS:
        m = spandrel.ModelLoader().load_from_file(os.path.join(d, f)).model.eval().float()
        with torch.no_grad():
            y = m(x)[0].numpy().astype(np.float64)
        flat = y.reshape(-1)
        idx = [(k * 2654435761) % flat.size for k in range(N)]
        vals = ", ".join(f"{flat[i]:.6}" for i in idx)
        print(f"/// {f}: output {list(y.shape)}, mean {flat.mean():.6}")
        print(f"pub const {name}_MEAN: f64 = {flat.mean():.8};")
        print(f"pub const {name}: [f32; N] = [{vals}];")

main()
