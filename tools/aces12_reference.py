# OpenColorIO's numbers for engine/tests/aces12.rs:
#   pip install opencolorio numpy
#   python tools/aces12_reference.py [aces_1.2/config.ocio] > engine/tests/aces12_ref/tables.rs
#
# ANALYTIC_* come from OCIO's built-in ACES transforms, the CTL as closed-form
# ops. LUT_* come from the ACES 1.2 OCIO config, whose Output spaces are baked
# 3D LUTs; they need the config (its luts/ beside it) and are empty without it.
import sys
import numpy as np
import PyOpenColorIO as ocio

SCENE = [  # ACEScg
    (0, 0, 0), (0.001, 0.001, 0.001), (0.01, 0.01, 0.01), (0.05, 0.05, 0.05),
    (0.18, 0.18, 0.18), (0.5, 0.5, 0.5), (1, 1, 1), (2, 2, 2), (4, 4, 4),
    (16, 16, 16), (100, 100, 100),
    (1, 0, 0), (0, 1, 0), (0, 0, 1), (0.18, 0.02, 0.01), (0.02, 0.1, 0.3),
    (0.9, 0.6, 0.1), (4, 0.5, 0.1), (0.3, 2, 0.4), (0.05, 0.2, 5),
    (0.7, 0.35, 0.9), (0.123, 0.456, 0.789), (8, 8, 0.2), (40, 2, 1),
]
CODES = [  # display code values
    (0, 0, 0), (0.01, 0.01, 0.01), (0.05, 0.05, 0.05), (0.1, 0.1, 0.1),
    (0.25, 0.25, 0.25), (0.5, 0.5, 0.5), (0.75, 0.75, 0.75), (0.9, 0.9, 0.9),
    (0.8, 0.2, 0.1), (0.1, 0.6, 0.3), (0.2, 0.3, 0.9), (0.9, 0.85, 0.7),
    (0.5, 0.4, 0.3), (0.3, 0.5, 0.7), (0.7, 0.3, 0.5), (0.4, 0.7, 0.2),
]
DISPLAYS = {"REC709": "DISPLAY - CIE-XYZ-D65_to_REC.1886-REC.709",
            "SRGB": "DISPLAY - CIE-XYZ-D65_to_sRGB"}
OUTPUTS = {"REC709": "Output - Rec.709", "SRGB": "Output - sRGB"}


def run(cpu, pts):
    a = np.array(pts, dtype=np.float32).copy()
    cpu.applyRGB(a)
    return a


def analytic(display, direction):
    g = ocio.GroupTransform()
    for name in ("ACEScg_to_ACES2065-1",
                 "ACES-OUTPUT - ACES2065-1_to_CIE-XYZ-D65 - SDR-VIDEO_1.0", display):
        g.appendTransform(ocio.BuiltinTransform(name))
    g.setDirection(direction)
    return ocio.Config.CreateRaw().getProcessor(g).getDefaultCPUProcessor()


def table(name, pts, vals):
    print(f"pub const {name}: &[([f32; 3], [f32; 3])] = &[")
    for p, v in zip(pts, vals):
        f = lambda t: "[" + ", ".join(f"{float(x):.8g}".join(["", "" if "." in f"{float(x):.8g}" or "e" in f"{float(x):.8g}" else ".0"]) for x in t) + "]"
        print(f"    ({f(p)}, {f(v)}),")
    print("];")


print("// Generated by tools/aces12_reference.py, OpenColorIO", ocio.__version__)
print("// (input, output). Forward: ACEScg -> display codes, clipped to 0..1 as the ODTs clip.")
print("// Inverse: display codes -> ACEScg.")
for key, display in DISPLAYS.items():
    fwd = np.clip(run(analytic(display, ocio.TRANSFORM_DIR_FORWARD), SCENE), 0, 1)
    table(f"ANALYTIC_FWD_{key}", SCENE, fwd)
    table(f"ANALYTIC_INV_{key}", CODES, run(analytic(display, ocio.TRANSFORM_DIR_INVERSE), CODES))

cfg = ocio.Config.CreateFromFile(sys.argv[1]) if len(sys.argv) > 1 else None
for key, out in OUTPUTS.items():
    fwd = run(cfg.getProcessor("ACES - ACEScg", out).getDefaultCPUProcessor(), SCENE) if cfg else []
    inv = run(cfg.getProcessor(out, "ACES - ACEScg").getDefaultCPUProcessor(), CODES) if cfg else []
    table(f"LUT_FWD_{key}", SCENE if cfg else [], fwd)
    table(f"LUT_INV_{key}", CODES if cfg else [], inv)
